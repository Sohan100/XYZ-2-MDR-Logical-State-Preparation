import math
def eps(err,shots,r):
    pl=err/shots; return 0.5*(1-(1-2*pl)**(1/r))
def pool(runs,r):
    e=sum(a for a,b in runs); s=sum(b for a,b in runs)
    # replicate chi2
    p=e/s; chi=sum((a-p*b)**2/(p*b) for a,b in runs) if len(runs)>1 else 0
    return eps(e,s,r), e, s, chi, len(runs)-1
def rat(name, A, B, rA, rB=None, Bval=None, Berr=None):
    ea,na,sa,chi,dof=pool(A,rA)
    if Bval is None:
        eb,nb,sb,_,_=pool(B,rB); relb=1/math.sqrt(nb)
    else:
        eb=Bval; relb=1/math.sqrt(Berr)
    rel=math.sqrt(1/na+relb**2); R=ea/eb
    sf=max(1,math.sqrt(chi/dof)) if dof>0 else 1
    rel2=math.sqrt((sf**2)/na+relb**2)
    print(f"{name}: A={ea:.3e}({na}) B={eb:.3e} ratio={R:.3f}+-{R*rel:.3f} [rep-scaled +-{R*rel2:.3f}, chi2={chi:.2f}/{dof}] z={(1-R)/(R*rel2):.1f}")
