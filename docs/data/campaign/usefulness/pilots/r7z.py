import math
from scipy import stats, optimize
def eps(e,s,r): pl=e/s; return 0.5*(1-(1-2*pl)**(1/r))
def pool(runs,r):
    e=sum(a for a,b in runs); s=sum(b for a,b in runs); p=e/s
    chi=sum((a-p*b)**2/(p*b) for a,b in runs) if len(runs)>1 else 0
    return eps(e,s,r),e,chi,len(runs)-1,len(runs)
def z(name,A,rA,Bval,NB,fB=1.7,Bk=1):
    ea,N1,chi,dof,k=pool(A,rA); R=ea/Bval; L=abs(math.log(R))
    sa=math.sqrt(1/N1+1/NB)
    f1=max(1,math.sqrt(chi/dof)) if dof>0 else 1.7
    f2=fB if Bk==1 else 1
    sb=math.sqrt(f1**2/N1+f2**2/NB); zb=L/sb
    if dof>0 and f1>1:
        p=stats.t.sf(zb,dof); zbg=stats.norm.isf(p)
    else: zbg=zb
    zc=[L/math.sqrt(1/N1+1/NB+d*d/k) for d in (0.15,0.25,0.37)]
    try: ds=math.sqrt(k*((L/3)**2-1/N1-1/NB))
    except ValueError: ds=float('nan')
    print(f"{name}: R={R:.3f}+-{R*sa:.3f} chi2={chi:.2f}/{dof} (a)={L/sa:.2f} (b)={zb:.2f}->{zbg:.2f} (c)={zc[0]:.2f}/{zc[1]:.2f}/@0.37 {zc[2]:.2f} delta*={ds:.3f}")
