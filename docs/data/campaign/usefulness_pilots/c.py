import math
from scipy.optimize import brentq
from scipy import stats
def eps(e,s,r): return 0.5*(1-(1-2*e/s)**(1/r))
def run(name,A,rA,Bv,NB,fB=1.7,fB_single=True):
    e=sum(a for a,b in A); s=sum(b for a,b in A); ea=eps(e,s,rA); R=ea/Bv
    p=e/s; chi=sum((a-p*b)**2/(p*b) for a,b in A); dof=len(A)-1
    L=abs(math.log(R))
    za=L/math.sqrt(1/e+1/NB)
    f=max(1,math.sqrt(chi/dof)) if dof>0 else 1.7
    zb=L/math.sqrt(f**2/e+fB**2/NB)
    zb1=L/math.sqrt(f**2/e+1/NB)
    def zc(d): return L/math.sqrt(1/sum(1/(1/a+d*d) for a,b in A)+1/NB)
    try: ds=brentq(lambda d: zc(d)-3,0,3)
    except: ds=float('nan')
    print(f"{name}: R={R:.3f}({R*math.sqrt(1/e+1/NB):.3f}) N={e} chi2={chi:.2f}/{dof} a={za:.2f} b={zb:.2f} (bcompPois {zb1:.2f}) c={zc(0.15):.2f}/{zc(0.25):.2f} c065={zc(0.065):.2f} d*={ds:.3f}")
